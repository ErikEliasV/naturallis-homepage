export function productHref(product: Pick<Product, "slug" | "category">): string {
  return `/produtos/${product.category}/${product.slug}`;
}

export function productsByCategory(category: CategorySlug): Product[] {
  return PRODUCTS.filter((product) => product.category === category);
}

export function findProduct(category: string, slug: string): Product | undefined {
  return PRODUCTS.find((product) => product.category === category && product.slug === slug);
}

